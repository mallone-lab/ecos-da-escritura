for slug, L in S.items():
    os.makedirs(os.path.join(ROOT, 'stories', slug), exist_ok=True)
    out = []
    for i, x in enumerate(L):
        d = {'id': f'l{i + 1:02d}', 'text': x if isinstance(x, str) else x[0]}
        if not isinstance(x, str): d['say'] = x[1]
        out.append(d)
    json.dump(out, open(os.path.join(ROOT, 'stories', slug, 'lines.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
